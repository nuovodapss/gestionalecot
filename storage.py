"""Encrypted, versioned snapshot storage for the R8 Streamlit parity prototype.

No plaintext patient data reaches this module. The browser sends the AES-GCM
JSON envelope generated by the unchanged R8 crypto.

Local SQLite is ONLY for local testing: it is not durable on Streamlit Community
Cloud and this implementation does not provide access control or multiuser
clinical-safety assurances.
"""
from __future__ import annotations

import hashlib
import json
import os
import sqlite3
from dataclasses import dataclass
from pathlib import Path
from typing import Any

MAX_ENVELOPE_BYTES = 15 * 1024 * 1024


class StorageConflict(Exception):
    """A different editor saved a newer revision."""


class InvalidEnvelope(ValueError):
    pass


@dataclass(frozen=True)
class SavedSnapshot:
    revision: int
    envelope: str | None
    digest: str | None


def validate_envelope(envelope: str) -> str:
    if not isinstance(envelope, str) or not envelope:
        raise InvalidEnvelope("Backup cifrato mancante")
    if len(envelope.encode('utf-8')) > MAX_ENVELOPE_BYTES:
        raise InvalidEnvelope("Backup cifrato troppo grande per il prototipo")
    try:
        doc = json.loads(envelope)
    except json.JSONDecodeError as exc:
        raise InvalidEnvelope("Backup non JSON") from exc
    if not isinstance(doc, dict):
        raise InvalidEnvelope("Contenitore non valido")
    if doc.get('format') != 'COT_PERCORSI_ENCRYPTED_JSON':
        raise InvalidEnvelope("Formato di archivio R8 non riconosciuto")
    if doc.get('archiveVersion') not in (2, 3):
        raise InvalidEnvelope("Versione archivio non supportata")
    if doc.get('cipher') != 'AES-GCM-256' or doc.get('kdf') != 'PBKDF2-SHA-256':
        raise InvalidEnvelope("Cifratura non riconosciuta")
    iterations = doc.get('iterations')
    if not isinstance(iterations, int) or not (100_000 <= iterations <= 2_000_000):
        raise InvalidEnvelope("Parametri crittografici non validi")
    for field in ('salt', 'iv', 'ciphertext'):
        val=doc.get(field)
        if not isinstance(val, str) or len(val) < 12 or len(val) > MAX_ENVELOPE_BYTES:
            raise InvalidEnvelope(f"Parametro {field} non valido")
    # DO NOT decrypt; passwords remain inside the user's browser.
    return hashlib.sha256(envelope.encode('utf-8')).hexdigest()


class SqliteEncryptedStore:
    def __init__(self, path: str | Path):
        self.path = Path(path)
        self.path.parent.mkdir(parents=True, exist_ok=True)
        with self.connect() as db:
            db.executescript("""
                CREATE TABLE IF NOT EXISTS encrypted_snapshots (
                    revision INTEGER PRIMARY KEY,
                    envelope TEXT NOT NULL,
                    sha256 TEXT NOT NULL,
                    created_at TEXT NOT NULL DEFAULT (datetime('now'))
                );
                CREATE INDEX IF NOT EXISTS ix_encrypted_snapshots_date
                    ON encrypted_snapshots(created_at);
            """)

    def connect(self):
        db = sqlite3.connect(self.path, timeout=30, isolation_level=None)
        db.execute('PRAGMA journal_mode=WAL')
        db.execute('PRAGMA busy_timeout=30000')
        return db

    def latest(self) -> SavedSnapshot:
        with self.connect() as db:
            row = db.execute(
                'SELECT revision,envelope,sha256 FROM encrypted_snapshots ORDER BY revision DESC LIMIT 1'
            ).fetchone()
        return SavedSnapshot(*row) if row else SavedSnapshot(0, None, None)

    def put(self, envelope: str, expected_revision: int) -> SavedSnapshot:
        digest = validate_envelope(envelope)
        if not isinstance(expected_revision, int) or expected_revision < 0:
            raise ValueError('Revisione attesa non valida')
        with self.connect() as db:
            db.execute('BEGIN IMMEDIATE')
            try:
                current = db.execute('SELECT MAX(revision) FROM encrypted_snapshots').fetchone()[0] or 0
                if current != expected_revision:
                    raise StorageConflict(f'Revisione {current} già salvata da altra sessione (attesa {expected_revision})')
                version = current + 1
                db.execute('INSERT INTO encrypted_snapshots(revision,envelope,sha256) VALUES (?,?,?)',
                           (version, envelope, digest))
                db.execute('COMMIT')
            except BaseException:
                db.execute('ROLLBACK')
                raise
        return SavedSnapshot(version, envelope, digest)


